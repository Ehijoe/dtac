/// Which caching algorithm `replay_bench` drives the replayed log against.
#[derive(clap::ValueEnum, Clone, Copy, Debug, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Algorithm {
    /// DTAC's bot-aware randomized-eviction engine (the engine under test).
    Dtac,
    /// A standard, bot-unaware sharded LRU cache -- the baseline a
    /// `--algorithm lru` run is meant to be diffed against.
    Lru,
}

/// Where the cache engine and router read time from during a replay.
#[derive(clap::ValueEnum, Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
enum ClockMode {
    /// Simulated time taken from each record's logged timestamp, so `--speed` only
    /// changes how long the replay takes, not what it measures.
    Log,
    /// The real wall clock: decay and velocity happen on the replay's compressed
    /// timeline, so results depend on `--speed`. Reproduces pre-plan-002 behaviour.
    Wall,
}

#[derive(Parser, Debug)]
#[command(
    author,
    version,
    about = "Direct in-process DTAC Cache log replay benchmark"
)]
struct Args {
    /// Path to the NDJSON log file (generated by the Python generator)
    #[arg(short, long)]
    file: PathBuf,

    /// Cache capacity
    #[arg(short = 'c', long, default_value_t = 10_000)]
    capacity: usize,

    /// Concurrency level (number of concurrent tasks)
    #[arg(short = 'j', long, default_value_t = 128)]
    concurrency: usize,

    /// Payload size in bytes returned on a cache miss for records without
    /// `size_bytes` (logs from before variable sizes)
    #[arg(short = 's', long, default_value_t = 1024)]
    payload_size: usize,

    /// Playback speed multiplier relative to the recorded timestamps.
    /// 1.0 = realtime (what the log's timestamps actually encode); higher
    /// values replay faster. With `--clock log` (the default) this only
    /// changes how long the replay takes; with `--clock wall` it also
    /// compresses the timeline that decay and velocity are measured on.
    #[arg(long, default_value_t = 10_000.0)]
    speed: f64,

    /// Time source for score decay and request velocity.
    ///
    /// `log` sets a shared simulated clock to each record's timestamp just
    /// before its access. Known imprecision: the clock only moves forward, so
    /// with up to `--concurrency` tasks in flight a request can see a time a
    /// few milliseconds ahead of its own if a later record's task set the
    /// clock first. With half-lives of seconds this is negligible.
    #[arg(long, value_enum, default_value_t = ClockMode::Log)]
    clock: ClockMode,

    /// JSON file with `EngineConfig` fields; omitted fields keep their defaults.
    #[arg(long, value_name = "PATH")]
    engine_config: Option<PathBuf>,

    /// Ghost-cache capacity as a multiple of the main-cache capacity. Overrides
    /// `ghost_multiplier` from `--engine-config`.
    #[arg(long, value_name = "N")]
    ghost_multiplier: Option<usize>,

    /// Which caching algorithm to replay the log against. Run the tool
    /// twice, once per value, against the same log file to compare their
    /// hit rates.
    #[arg(short = 'a', long, value_enum, default_value_t = Algorithm::Dtac)]
    algorithm: Algorithm,

    #[command(flatten)]
    asn: AsnArgs,

    /// JSON file with `RouterConfig` fields; omitted fields keep their defaults.
    #[arg(long, value_name = "PATH")]
    router_config: Option<PathBuf>,

    /// Router prior bot rate in (0, 1). Overrides `prior_bot_rate` from
    /// `--router-config`; 0.5 reproduces the original zero prior.
    #[arg(long, value_name = "P")]
    prior_bot_rate: Option<f64>,

    /// Write every reported metric plus the run configuration to this JSON file.
    #[arg(long, value_name = "PATH")]
    json_out: Option<PathBuf>,

    /// Sample the Cache Pollution Index every N measurement requests (and at the end).
    #[arg(long, value_name = "N", default_value_t = 10_000)]
    cpi_sample_every: usize,

    /// Hide the progress bar and the Prometheus dump, for scripted runs.
    #[arg(short, long)]
    quiet: bool,
}

/// The run configuration written to `--json-out` next to the results.
#[derive(Serialize)]
struct RunInfo<'a> {
    file: &'a Path,
    algorithm: Algorithm,
    capacity: usize,
    concurrency: usize,
    payload_size: usize,
    speed: f64,
    clock: ClockMode,
    asn_db: &'a [PathBuf],
    /// Effective router config; `None` for engines without a router.
    router_config: Option<RouterConfig>,
    /// Effective engine config; `None` for the baselines.
    engine_config: Option<EngineConfig>,
    /// The log's `.meta.json` sidecar (seed, ratio, generator arguments), if present.
    log_meta: Option<serde_json::Value>,
    /// The bench's git commit, with `-dirty` if the tree had changes.
    git_commit: Option<String>,
}

/// The whole `--json-out` document.
#[derive(Serialize)]
struct JsonOut<'a> {
    run: RunInfo<'a>,
    results: &'a Report,
}

/// `traffic.ndjson` -> `traffic.meta.json`, the generator's sidecar.
fn meta_path(log: &Path) -> PathBuf {
    log.with_extension("meta.json")
}

/// Reads the log's `.meta.json` sidecar, or `None` if it doesn't exist (older logs).
fn load_log_meta(log: &Path) -> Result<Option<serde_json::Value>, Box<dyn std::error::Error>> {
    let path = meta_path(log);
    if !path.exists() {
        return Ok(None);
    }
    Ok(Some(serde_json::from_reader(BufReader::new(File::open(
        path,
    )?))?))
}

/// The commit the bench was built from: `DTAC_GIT_COMMIT` at build time if set, else
/// `git rev-parse HEAD` in the source tree at runtime.
fn git_commit() -> Option<String> {
    if let Some(commit) = option_env!("DTAC_GIT_COMMIT") {
        return Some(commit.to_string());
    }
    let git = |args: &[&str]| {
        std::process::Command::new("git")
            .arg("-C")
            .arg(env!("CARGO_MANIFEST_DIR"))
            .args(args)
            .output()
            .ok()
            .filter(|out| out.status.success())
            .map(|out| String::from_utf8_lossy(&out.stdout).trim().to_string())
    };
    let commit = git(&["rev-parse", "HEAD"])?;
    let dirty = git(&["status", "--porcelain", "--untracked-files=no"])
        .is_some_and(|status| !status.is_empty());
    Some(if dirty {
        format!("{commit}-dirty")
    } else {
        commit
    })
}

/// Builds the router from `--router-config`, `--prior-bot-rate` and the ASN flags.
fn build_router(args: &Args) -> Result<HeuristicRouter, Box<dyn std::error::Error>> {
    let mut config = match &args.router_config {
        Some(path) => serde_json::from_reader(BufReader::new(File::open(path)?))?,
        None => RouterConfig::default(),
    };
    if let Some(prior) = args.prior_bot_rate {
        config.prior_bot_rate = prior;
    }

    let asn_db = args.asn.load()?.unwrap_or_default();
    if !args.asn.asn_db.is_empty() {
        println!(
            "ASN database:   {} IPv4 + {} IPv6 ranges from {:?}",
            asn_db.v4_range_count(),
            asn_db.v6_range_count(),
            args.asn.asn_db
        );
    }
    println!("Router config:  {}", serde_json::to_string(&config)?);

    Ok(HeuristicRouter::with_config(config, asn_db)?)
}

/// Builds the engine config from `--engine-config` and `--ghost-multiplier`.
fn build_engine_config(args: &Args) -> Result<EngineConfig, Box<dyn std::error::Error>> {
    let mut config = match &args.engine_config {
        Some(path) => serde_json::from_reader(BufReader::new(File::open(path)?))?,
        None => EngineConfig::default(),
    };
    if let Some(multiplier) = args.ghost_multiplier {
        config.ghost_multiplier = multiplier;
    }
    println!("Engine config:  {}", serde_json::to_string(&config)?);
    Ok(config)
}

/// Moves the simulated clock to a record's logged `timestamp` (in seconds).
///
/// The clock never moves backwards, so after every record has been dispatched it
/// reads the latest timestamp, regardless of the order the tasks ran in.
fn set_log_time(clock: &ManualClock, timestamp: f64) {
    // `as` saturates: negative or NaN timestamps map to 0.
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    clock.set_millis((timestamp * 1000.0) as u64);
}

/// Logs per-request router/cache events to stderr only when `RUST_LOG` is set, since
/// per-request logging would otherwise dominate the measured throughput.
fn init_tracing_if_requested() {
    if let Ok(filter) = std::env::var("RUST_LOG") {
        tracing_subscriber::fmt()
            .with_env_filter(tracing_subscriber::EnvFilter::new(filter))
            .with_writer(std::io::stderr)
            .init();
    }
}

// Only reachable via the `#[serde(default = ...)]` attribute below, which
// `cargo test --bin` sometimes flags as dead since `main` (the only real
// caller of `serde_json::from_str::<LogRecord>`) isn't exercised by tests.
#[allow(dead_code)]
fn default_ip() -> String {
    "127.0.0.1".to_string()
}

/// Which part of a replay a record belongs to. Warm-up records populate the
/// cache exactly like any other access but are excluded from
/// `BenchMetrics`/timing so the final report reflects steady-state
/// (post-warm-up) behavior.
#[derive(Debug, Deserialize, Clone, Copy, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
enum Phase {
    Warmup,
    Measurement,
}

// Stale logs generated before the `phase` field existed count fully,
// matching the tool's original (warm-up-unaware) behavior.
#[allow(dead_code)]
const fn default_phase() -> Phase {
    Phase::Measurement
}

#[derive(Debug, Deserialize, Clone)]
#[allow(dead_code)]
struct LogRecord {
    timestamp: f64,
    method: String,
    path: String,
    headers: HashMap<String, String>,
    traffic_type: String, // "human" or "bot"
    #[serde(default = "default_ip")]
    ip: String,
    #[serde(default = "default_phase")]
    phase: Phase,
    /// Payload size of the requested item; absent in older logs.
    #[serde(default)]
    size_bytes: Option<u64>,
    /// `naive` or `stealthy` for bot records; absent for humans and older logs.
    #[serde(default)]
    bot_kind: Option<String>,
    /// `new` or `returning` for human records; absent for bots and older logs.
    #[serde(default)]
    visitor: Option<String>,
}

/// Shared state every replayed record needs.
struct ReplayCtx {
    engine: Engine,
    log_clock: Option<Arc<ManualClock>>,
    metrics: Arc<BenchMetrics>,
    /// One zeroed buffer as large as the biggest payload. Each fetch returns a `slice`
    /// of it, so allocation doesn't distort the timings and payloads cost no RSS.
    payload: bytes::Bytes,
    /// Size used for records without `size_bytes`.
    default_size: u64,
}

impl ReplayCtx {
    /// The payload size for `record`: its `size_bytes`, or `--payload-size`.
    fn size_of(&self, record: &LogRecord) -> u64 {
        record.size_bytes.unwrap_or(self.default_size)
    }

    /// A payload of `size` bytes, sliced from the shared buffer.
    fn payload_of(&self, size: u64) -> bytes::Bytes {
        let len = usize::try_from(size).map_or(self.payload.len(), |n| n.min(self.payload.len()));
        self.payload.slice(..len)
    }
}

/// Parses `raw` as an `IpAddr`, falling back to `127.0.0.1` if it's missing
/// or malformed (e.g. a stale log generated before the `ip` field existed).
fn resolve_ip(raw: &str) -> IpAddr {
    raw.parse().unwrap_or(IpAddr::V4(Ipv4Addr::LOCALHOST))
}

/// Computes the wall-clock instant at which a record with the given logged
/// `timestamp` should be dispatched, relative to `bench_start` and scaled by
/// `speed` (1.0 = realtime, higher = faster).
fn target_instant(bench_start: TokioInstant, timestamp: f64, speed: f64) -> TokioInstant {
    bench_start + Duration::from_secs_f64(timestamp / speed)
}

/// Reads every non-blank line of the NDJSON log at `path` into memory.
fn load_records(path: &Path) -> Result<Vec<LogRecord>, Box<dyn std::error::Error>> {
    println!("Loading log entries into memory from {}...", path.display());
    let reader = BufReader::with_capacity(32 * 1024 * 1024, File::open(path)?);

    let mut records: Vec<LogRecord> = Vec::new();
    for line in reader.lines() {
        let line = line?;
        if !line.trim().is_empty() {
            records.push(serde_json::from_str(&line)?);
        }
    }
    Ok(records)
}

/// Prints the run's parameters: sizes, algorithm, clock mode and playback speed.
fn print_run_header(args: &Args, records: &[LogRecord]) {
    println!("Cache Capacity: {}", args.capacity);
    println!("Worker Concurrency: {}", args.concurrency);
    println!("Algorithm:              {:?}", args.algorithm);
    println!(
        "Clock:          {:?}{}",
        args.clock,
        match args.clock {
            ClockMode::Log => " (simulated from log timestamps; --speed does not affect results)",
            ClockMode::Wall => " (wall clock; results depend on --speed)",
        }
    );
    let is_realtime = (args.speed - 1.0).abs() < f64::EPSILON;
    println!(
        "Playback Speed: {:.2}x{}",
        args.speed,
        if is_realtime { " (realtime)" } else { "" }
    );
    if let (Some(first), Some(last)) = (records.first(), records.last()) {
        let logged_span_secs = (last.timestamp - first.timestamp).max(0.0);
        println!(
            "Estimated wall time: {:.1}s ({:.1}s of logged traffic at {:.2}x)",
            logged_span_secs / args.speed,
            logged_span_secs,
            args.speed
        );
    }
}

/// Builds the cache selected by `--algorithm`. For DTAC this prints the effective
/// router and engine configs, and wires in `log_clock` when replaying on log time.
/// Main-cache evictions are reported to `metrics`' ledger.
fn build_engine(
    args: &Args,
    log_clock: Option<&Arc<ManualClock>>,
    metrics: &Arc<BenchMetrics>,
) -> Result<Engine, Box<dyn std::error::Error>> {
    let metrics = metrics.clone();
    let on_evict = Arc::new(move |key: &String| metrics.ledger.on_evict(key));
    Ok(match args.algorithm {
        Algorithm::Dtac => {
            let mut builder = DtacCache::<String, bytes::Bytes>::builder(args.capacity)
                .router(build_router(args)?)
                .engine_config(build_engine_config(args)?)?
                .eviction_listener(on_evict);
            if let Some(clock) = log_clock {
                builder = builder.clock(clock.clone());
            }
            Engine::Dtac(Arc::new(builder.build()))
        }
        Algorithm::Lru => Engine::Lru(Arc::new(
            BaselineLruEngine::<String, bytes::Bytes>::new(args.capacity)
                .with_eviction_listener(on_evict),
        )),
    })
}

/// Replays one log record through the engine and records its outcome in the metrics.
///
/// `seq` is the record's position in the log; it picks which latency stripe to record into.
async fn replay_record(record: LogRecord, seq: usize, ctx: &ReplayCtx) {
    let metrics = &ctx.metrics;
    let is_bot = record.traffic_type == "bot";
    let is_measurement = record.phase == Phase::Measurement;
    let size = ctx.size_of(&record);
    let payload = ctx.payload_of(size);

    // Track total counts per category -- warm-up records still run
    // through the real cache below, but never touch BenchMetrics.
    if is_measurement {
        metrics.record_request(is_bot, size);
    }

    let path = record.path.clone();
    let key = record.path.clone();
    let origin = if is_bot { Origin::Bot } else { Origin::Human };
    let label = Label::of(
        &record.traffic_type,
        record.visitor.as_deref(),
        record.bot_kind.as_deref(),
    );

    // Closure triggered ONLY on a cache miss. The ledger also tracks warm-up fetches, since
    // warm-up admissions are still resident when measurement starts.
    let fetch_from_origin = |fetched: &String| {
        metrics.ledger.on_fetch(fetched, origin, size);
        if is_measurement {
            metrics.record_miss(is_bot, size);
        }
        async move { payload }
    };

    if let Some(clock) = &ctx.log_clock {
        set_log_time(clock, record.timestamp);
    }

    let req_start = Instant::now();
    let phases = match &ctx.engine {
        Engine::Dtac(cache) => {
            // RequestData is only built for the Dtac arm -- the Lru
            // baseline is bot-unaware by definition, so building it
            // there would be pure overhead skewing the two
            // algorithms' measured per-request latency against
            // each other without affecting hit-rate correctness.
            let req_data = RequestData {
                ip_address: resolve_ip(&record.ip),
                path: record.path,
                method: record.method,
                headers: record.headers,
            };
            let (_, stats) = cache
                .access_with_stats(path, req_data, fetch_from_origin)
                .await;
            if is_measurement {
                let sample = Sample {
                    bot_prob: stats.bot_prob,
                    label,
                };
                metrics.classifier.with(seq, |samples| samples.push(sample));
            }
            Some((stats.router_time, stats.engine_time))
        }
        Engine::Lru(baseline) => {
            baseline.access(path, fetch_from_origin).await;
            None
        }
    };
    let total = req_start.elapsed();
    if is_measurement {
        metrics.total_duration_us.fetch_add(
            u64::try_from(total.as_micros()).unwrap_or(u64::MAX),
            Ordering::Relaxed,
        );
        let (proxy, cache) =
            phases.map_or((None, total), |(router, engine)| (Some(router), engine));
        metrics.latency.with(seq, |h| h.record(proxy, cache, total));
    }
    if !is_bot {
        metrics.ledger.on_human_request(&key);
    }
}

/// The progress bar for `len` records, hidden with `--quiet`.
fn progress_bar(quiet: bool, len: usize) -> Result<ProgressBar, Box<dyn std::error::Error>> {
    let pb = if quiet {
        ProgressBar::hidden()
    } else {
        ProgressBar::new(len as u64)
    };
    pb.set_style(
        ProgressStyle::default_bar()
            .template(
                "{spinner:.green} [{elapsed_precise}] [{bar:40.cyan/blue}] {pos}/{len} ({per_sec})",
            )?
            .progress_chars("#>-"),
    );
    Ok(pb)
}

/// Replays every record and returns the wall time of the measurement phase.
///
/// Records are dispatched paced by their logged timestamps (scaled by `--speed`), while a
/// semaphore bounds how many may be in flight at once -- decoupling "when a request is
/// paced to start" from "how many are concurrently executing," matching a real traffic
/// replay.
async fn dispatch(
    records: Vec<LogRecord>,
    ctx: &Arc<ReplayCtx>,
    args: &Args,
    pb: &ProgressBar,
) -> Result<Duration, Box<dyn std::error::Error>> {
    let mut start_time = Instant::now();
    let mut measurement_started = false;
    let mut measurement_dispatched = 0_usize;
    let bench_start = TokioInstant::now();
    let semaphore = Arc::new(Semaphore::new(args.concurrency));
    let mut join_set = tokio::task::JoinSet::new();

    for (seq, record) in records.into_iter().enumerate() {
        sleep_until(target_instant(bench_start, record.timestamp, args.speed)).await;

        // Warm-up records still exercise the real cache (below) so it gets
        // populated for whichever --algorithm is selected, but the
        // metrics-relevant clock only starts once measurement begins, so
        // throughput/latency/hit-rate numbers reflect a warmed cache, not
        // the warm-up pass itself.
        if !measurement_started && record.phase == Phase::Measurement {
            measurement_started = true;
            start_time = Instant::now();
            ctx.metrics.ledger.start_measuring();
            pb.println("Warm-up complete -- beginning measurement phase.");
        }
        if record.phase == Phase::Measurement {
            if measurement_dispatched > 0
                && measurement_dispatched.is_multiple_of(args.cpi_sample_every)
            {
                ctx.metrics.ledger.sample(&ctx.engine.resident_keys());
            }
            measurement_dispatched += 1;
        }

        // If --speed is set too low for the given --concurrency, this is
        // where the dispatch loop will stall waiting for a free slot --
        // intentional backpressure, not a bug.
        let permit = semaphore.clone().acquire_owned().await?;
        let ctx = ctx.clone();
        let pb = pb.clone();

        join_set.spawn(async move {
            let _permit = permit; // held for the duration of this task, released on completion

            replay_record(record, seq, &ctx).await;

            pb.inc(1);
        });
    }

    // Drain remaining in-flight work after the dispatch loop finishes issuing records.
    while join_set.join_next().await.is_some() {}
    ctx.metrics.ledger.sample(&ctx.engine.resident_keys());

    pb.finish_with_message("Replay Complete");
    Ok(start_time.elapsed())
}

/// Writes the report and the run configuration to `path` (`--json-out`).
fn write_json_out(
    path: &Path,
    args: &Args,
    engine: &Engine,
    report: &Report,
) -> Result<(), Box<dyn std::error::Error>> {
    let (router_config, engine_config) = match engine {
        Engine::Dtac(cache) => (
            Some(*cache.router().config()),
            Some(*cache.engine().config()),
        ),
        Engine::Lru(_) => (None, None),
    };
    let out = JsonOut {
        run: RunInfo {
            file: &args.file,
            algorithm: args.algorithm,
            capacity: args.capacity,
            concurrency: args.concurrency,
            payload_size: args.payload_size,
            speed: args.speed,
            clock: args.clock,
            asn_db: &args.asn.asn_db,
            router_config,
            engine_config,
            log_meta: load_log_meta(&args.file)?,
            git_commit: git_commit(),
        },
        results: report,
    };
    serde_json::to_writer_pretty(std::io::BufWriter::new(File::create(path)?), &out)?;
    println!("Wrote {}", path.display());
    Ok(())
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args = Args::parse();
    if args.speed <= 0.0 {
        eprintln!("--speed must be greater than 0.0 (got {})", args.speed);
        std::process::exit(1);
    }
    if args.cpi_sample_every == 0 {
        eprintln!("--cpi-sample-every must be at least 1");
        std::process::exit(1);
    }
    init_tracing_if_requested();

    // 1. Initialize Prometheus & OpenTelemetry Registry
    let registry = init_metrics()?;

    // 2. Load NDJSON records into memory
    let records = load_records(&args.file)?;
    println!("Loaded {} records into memory.", records.len());
    print_run_header(&args, &records);

    // 3. Initialize Cache & Metrics Tracker
    let log_clock = (args.clock == ClockMode::Log).then(|| Arc::new(ManualClock::new(0)));
    let default_size = args.payload_size as u64;
    let max_size = records
        .iter()
        .filter_map(|r| r.size_bytes)
        .fold(default_size, u64::max);
    let metrics = Arc::new(BenchMetrics::default());
    let ctx = Arc::new(ReplayCtx {
        engine: build_engine(&args, log_clock.as_ref(), &metrics)?,
        log_clock,
        metrics,
        payload: bytes::Bytes::from(vec![0u8; usize::try_from(max_size)?]),
        default_size,
    });

    // 4. Replay
    let pb = progress_bar(args.quiet, records.len())?;
    let total_wall_time = dispatch(records, &ctx, &args, &pb).await?;

    // 5. Gather and compute final statistics
    let report = Report::new(&ctx.metrics, total_wall_time);
    report.print(args.algorithm);
    if !args.quiet {
        print_prometheus(&registry);
    }
    if let Engine::Dtac(cache) = &ctx.engine {
        // Metadata overhead: the ghost cache holds keys and scores but no payloads.
        println!(
            "Final cache entries: {} main, {} ghost (bound {} per shard)",
            cache.engine().len(),
            cache.engine().ghost_len(),
            cache.engine().ghost_capacity_per_shard()
        );
    }
    if let Some(path) = &args.json_out {
        write_json_out(path, &args, &ctx.engine, &report)?;
    }

    Ok(())
}

