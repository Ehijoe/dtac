//! Replay script that doesn't make network requests for benchmarking

use clap::Parser;
use dtac::dtac_cache::DtacCache;
use dtac::types::RequestData;
use futures::StreamExt;
use indicatif::{ProgressBar, ProgressStyle};
use prometheus::{Encoder, TextEncoder};
use serde::Deserialize;
use std::collections::HashMap;
use std::fs::File;
use std::io::{BufRead, BufReader};
use std::net::{IpAddr, Ipv4Addr};
use std::path::PathBuf;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;
use std::time::Instant;

#[derive(Parser, Debug)]
#[command(author, version, about = "Direct in-process DTAC Cache log replay benchmark")]
struct Args {
    /// Path to the NDJSON log file (generated by the Python generator)
    #[arg(short, long)]
    file: PathBuf,

    /// Cache capacity
    #[arg(short = 'c', long, default_value_t = 10_000)]
    capacity: usize,

    /// Concurrency level (number of concurrent tasks)
    #[arg(short = 'j', long, default_value_t = 128)]
    concurrency: usize,

    /// Simulated payload size in bytes returned on cache miss
    #[arg(short = 's', long, default_value_t = 1024)]
    payload_size: usize,
}

#[derive(Debug, Deserialize, Clone)]
#[allow(dead_code)]
struct LogRecord {
    timestamp: f64,
    method: String,
    path: String,
    headers: HashMap<String, String>,
    traffic_type: String, // "human" or "bot"
}

#[derive(Default)]
struct BenchMetrics {
    // Total counters
    total_requests: AtomicU64,
    cache_miss_fetches: AtomicU64, // Increment when fetch_from_origin is called

    // Disaggregated human vs bot counters
    human_requests: AtomicU64,
    human_misses: AtomicU64,
    bot_requests: AtomicU64,
    bot_misses: AtomicU64,

    // Timing
    total_duration_us: AtomicU64,
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args = Args::parse();

    // 1. Initialize Prometheus & OpenTelemetry Registry
    let registry = prometheus::Registry::new();
    let exporter = opentelemetry_prometheus::exporter()
        .with_registry(registry.clone())
        .build()
        .expect("Failed to build prometheus exporter");
    let meter_provider = opentelemetry_sdk::metrics::SdkMeterProvider::builder()
        .with_reader(exporter)
        .build();
    opentelemetry::global::set_meter_provider(meter_provider);

    // 2. Load NDJSON records into memory
    println!("Loading log entries into memory from {:?}...", args.file);
    let file = File::open(&args.file)?;
    let reader = BufReader::with_capacity(32 * 1024 * 1024, file);

    let mut records: Vec<LogRecord> = Vec::new();
    for line in reader.lines() {
        let line = line?;
        if !line.trim().is_empty() {
            let record: LogRecord = serde_json::from_str(&line)?;
            records.push(record);
        }
    }

    let total_records = records.len();
    println!("Loaded {total_records} records into memory.");
    println!("Cache Capacity: {}", args.capacity);
    println!("Worker Concurrency: {}", args.concurrency);

    // 3. Initialize Cache & Metrics Tracker
    let cache = Arc::new(DtacCache::<String, bytes::Bytes>::new(args.capacity));
    let metrics = Arc::new(BenchMetrics::default());
    let default_payload = bytes::Bytes::from(vec![0u8; args.payload_size]);

    let pb = ProgressBar::new(total_records as u64);
    pb.set_style(
        ProgressStyle::default_bar()
            .template("{spinner:.green} [{elapsed_precise}] [{bar:40.cyan/blue}] {pos}/{len} ({per_sec})")?
            .progress_chars("#>-"),
    );

    let start_time = Instant::now();

    // 4. Stream records into the DTAC cache engine directly
    futures::stream::iter(records)
        .for_each_concurrent(args.concurrency, |record| {
            let cache = cache.clone();
            let metrics = metrics.clone();
            let pb = pb.clone();
            let payload = default_payload.clone();

            async move {
                let is_bot = record.traffic_type == "bot";
                
                // Track total counts per category
                metrics.total_requests.fetch_add(1, Ordering::Relaxed);
                if is_bot {
                    metrics.bot_requests.fetch_add(1, Ordering::Relaxed);
                } else {
                    metrics.human_requests.fetch_add(1, Ordering::Relaxed);
                }

                let req_data = RequestData {
                    ip_address: IpAddr::V4(Ipv4Addr::new(127, 0, 0, 1)),
                    path: record.path.clone(),
                    method: record.method,
                    headers: record.headers,
                };

                let path = record.path;
                let metrics_fetch = metrics.clone();

                // Closure triggered ONLY on a cache miss
                let fetch_from_origin = |_key: &String| {
                    let metrics_fetch = metrics_fetch.clone();
                    let payload = payload.clone();
                    async move {
                        metrics_fetch.cache_miss_fetches.fetch_add(1, Ordering::Relaxed);
                        if is_bot {
                            metrics_fetch.bot_misses.fetch_add(1, Ordering::Relaxed);
                        } else {
                            metrics_fetch.human_misses.fetch_add(1, Ordering::Relaxed);
                        }
                        payload
                    }
                };

                let req_start = Instant::now();
                let _ = cache.access(path, req_data, fetch_from_origin).await;
                metrics.total_duration_us.fetch_add(req_start.elapsed().as_micros() as u64, Ordering::Relaxed);

                pb.inc(1);
            }
        })
        .await;

    pb.finish_with_message("Replay Complete");
    let total_wall_time = start_time.elapsed();

    // 5. Gather and compute final statistics
    print_results(&metrics, total_wall_time, &registry);

    Ok(())
}

fn print_results(
    m: &BenchMetrics,
    total_time: std::time::Duration,
    registry: &prometheus::Registry,
) {
    let total_reqs = m.total_requests.load(Ordering::Relaxed);
    let total_misses = m.cache_miss_fetches.load(Ordering::Relaxed);
    let total_hits = total_reqs.saturating_sub(total_misses);

    let human_reqs = m.human_requests.load(Ordering::Relaxed);
    let human_misses = m.human_misses.load(Ordering::Relaxed);
    let human_hits = human_reqs.saturating_sub(human_misses);

    let bot_reqs = m.bot_requests.load(Ordering::Relaxed);
    let bot_misses = m.bot_misses.load(Ordering::Relaxed);
    let bot_hits = bot_reqs.saturating_sub(bot_misses);

    let total_us = m.total_duration_us.load(Ordering::Relaxed);
    let avg_latency_us = if total_reqs > 0 { total_us as f64 / total_reqs as f64 } else { 0.0 };
    let rps = total_reqs as f64 / total_time.as_secs_f64();

    let overall_hit_rate = if total_reqs > 0 { (total_hits as f64 / total_reqs as f64) * 100.0 } else { 0.0 };
    let human_hit_rate = if human_reqs > 0 { (human_hits as f64 / human_reqs as f64) * 100.0 } else { 0.0 };
    let bot_hit_rate = if bot_reqs > 0 { (bot_hits as f64 / bot_reqs as f64) * 100.0 } else { 0.0 };

    println!("\n========================================================");
    println!("              DTAC DIRECT BENCHMARK REPORT              ");
    println!("========================================================");
    println!("Elapsed Time:           {:.3?}", total_time);
    println!("Throughput:             {:.2} ops/sec", rps);
    println!("Average Access Time:    {:.3} µs", avg_latency_us);
    println!("--------------------------------------------------------");
    println!("Total Requests:         {}", total_reqs);
    println!("Total Cache Hits:       {} ({:.2}%)", total_hits, overall_hit_rate);
    println!("Total Cache Misses:     {} ({:.2}%)", total_misses, 100.0 - overall_hit_rate);
    println!("--------------------------------------------------------");
    println!("Human Requests:         {}", human_reqs);
    println!("Human Cache Hit Rate:   {:.2}% ({} hits / {} misses)", human_hit_rate, human_hits, human_misses);
    println!("--------------------------------------------------------");
    println!("Bot Requests:           {}", bot_reqs);
    println!("Bot Cache Hit Rate:     {:.2}% ({} hits / {} misses)", bot_hit_rate, bot_hits, bot_misses);
    println!("========================================================");

    // Print internal Prometheus metrics gathered by DTAC / OpenTelemetry
    println!("\n--- Raw Prometheus Metrics Registry Output ---");
    let encoder = TextEncoder::new();
    let mut buffer = vec![];
    let metric_families = registry.gather();
    if let Ok(_) = encoder.encode(&metric_families, &mut buffer) {
        if let Ok(text) = String::from_utf8(buffer) {
            println!("{}", text);
        }
    }
}