/// Which caching algorithm `replay_bench` drives the replayed log against.
#[derive(clap::ValueEnum, Clone, Copy, Debug)]
enum Algorithm {
    /// DTAC's bot-aware randomized-eviction engine (the engine under test).
    Dtac,
    /// A standard, bot-unaware sharded LRU cache -- the baseline a
    /// `--algorithm lru` run is meant to be diffed against.
    Lru,
}

#[derive(Parser, Debug)]
#[command(author, version, about = "Direct in-process DTAC Cache log replay benchmark")]
struct Args {
    /// Path to the NDJSON log file (generated by the Python generator)
    #[arg(short, long)]
    file: PathBuf,

    /// Cache capacity
    #[arg(short = 'c', long, default_value_t = 10_000)]
    capacity: usize,

    /// Concurrency level (number of concurrent tasks)
    #[arg(short = 'j', long, default_value_t = 128)]
    concurrency: usize,

    /// Simulated payload size in bytes returned on cache miss
    #[arg(short = 's', long, default_value_t = 1024)]
    payload_size: usize,

    /// Playback speed multiplier relative to the recorded timestamps.
    /// 1.0 = realtime (what the log's timestamps actually encode); higher
    /// values replay faster. Defaults to a fast constant so existing
    /// quick-iteration runs stay quick; pass `--speed 1.0` to exercise the
    /// router's per-IP velocity heuristic against realistic request cadence.
    #[arg(long, default_value_t = 10_000.0)]
    speed: f64,

    /// Which caching algorithm to replay the log against. Run the tool
    /// twice, once per value, against the same log file to compare their
    /// hit rates.
    #[arg(short = 'a', long, value_enum, default_value_t = Algorithm::Dtac)]
    algorithm: Algorithm,
}

// Only reachable via the `#[serde(default = ...)]` attribute below, which
// `cargo test --bin` sometimes flags as dead since `main` (the only real
// caller of `serde_json::from_str::<LogRecord>`) isn't exercised by tests.
#[allow(dead_code)]
fn default_ip() -> String {
    "127.0.0.1".to_string()
}

/// Which part of a replay a record belongs to. Warm-up records populate the
/// cache exactly like any other access but are excluded from
/// `BenchMetrics`/timing so the final report reflects steady-state
/// (post-warm-up) behavior.
#[derive(Debug, Deserialize, Clone, Copy, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
enum Phase {
    Warmup,
    Measurement,
}

// Stale logs generated before the `phase` field existed count fully,
// matching the tool's original (warm-up-unaware) behavior.
#[allow(dead_code)]
const fn default_phase() -> Phase {
    Phase::Measurement
}

#[derive(Debug, Deserialize, Clone)]
#[allow(dead_code)]
struct LogRecord {
    timestamp: f64,
    method: String,
    path: String,
    headers: HashMap<String, String>,
    traffic_type: String, // "human" or "bot"
    #[serde(default = "default_ip")]
    ip: String,
    #[serde(default = "default_phase")]
    phase: Phase,
}

/// Parses `raw` as an `IpAddr`, falling back to `127.0.0.1` if it's missing
/// or malformed (e.g. a stale log generated before the `ip` field existed).
fn resolve_ip(raw: &str) -> IpAddr {
    raw.parse().unwrap_or(IpAddr::V4(Ipv4Addr::LOCALHOST))
}

/// Computes the wall-clock instant at which a record with the given logged
/// `timestamp` should be dispatched, relative to `bench_start` and scaled by
/// `speed` (1.0 = realtime, higher = faster).
fn target_instant(bench_start: TokioInstant, timestamp: f64, speed: f64) -> TokioInstant {
    bench_start + Duration::from_secs_f64(timestamp / speed)
}

#[derive(Default)]
struct BenchMetrics {
    // Total counters
    total_requests: AtomicU64,
    cache_miss_fetches: AtomicU64, // Increment when fetch_from_origin is called

    // Disaggregated human vs bot counters
    human_requests: AtomicU64,
    human_misses: AtomicU64,
    bot_requests: AtomicU64,
    bot_misses: AtomicU64,

    // Timing
    total_duration_us: AtomicU64,
}

/// A standard, bot-unaware sharded LRU cache: the baseline that
/// `--algorithm lru` benchmarks against DTAC's own engine. Shards the same
/// way as `DtacCacheEngine` (same `NUM_SHARDS`, same capacity-per-shard
/// math) so the comparison isolates eviction/admission policy rather than
/// lock granularity or capacity partitioning. Bench-tool-only -- not part
/// of the published `dtac` library.
struct BaselineLruEngine<K, P> {
    shards: Vec<Mutex<LruCache<K, P>>>,
}

impl<K: Eq + Hash + Clone, P: Clone> BaselineLruEngine<K, P> {
    fn new(total_capacity: usize) -> Self {
        let capacity_per_shard = (total_capacity / NUM_SHARDS).max(1);
        let cap = NonZeroUsize::new(capacity_per_shard).expect("capacity_per_shard is .max(1)'d above, never zero");
        let shards = (0..NUM_SHARDS).map(|_| Mutex::new(LruCache::new(cap))).collect();
        Self { shards }
    }

    fn get_shard_id(key: &K) -> usize {
        let mut hasher = DefaultHasher::new();
        key.hash(&mut hasher);
        (hasher.finish() as usize) % NUM_SHARDS
    }

    async fn access<F, Fut>(&self, key: K, fetch_from_origin: F) -> P
    where
        F: FnOnce(&K) -> Fut,
        Fut: Future<Output = P>,
    {
        let shard_id = Self::get_shard_id(&key);

        let hit = {
            let mut shard = self.shards[shard_id].lock().expect("baseline LRU shard mutex poisoned");
            shard.get(&key).cloned() // lru's get() already promotes to MRU
        };
        if let Some(payload) = hit {
            return payload;
        }

        // Release the lock before awaiting, matching DtacCacheEngine's
        // convention of never holding a shard lock across an await point.
        let payload = fetch_from_origin(&key).await;
        let mut shard = self.shards[shard_id].lock().expect("baseline LRU shard mutex poisoned");
        shard.put(key, payload.clone()); // idempotent per key: no orphan-entry risk
        payload
    }
}

#[derive(Clone)]
enum Engine {
    Dtac(Arc<DtacCache<String, bytes::Bytes>>),
    Lru(Arc<BaselineLruEngine<String, bytes::Bytes>>),
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args = Args::parse();
    if args.speed <= 0.0 {
        eprintln!("--speed must be greater than 0.0 (got {})", args.speed);
        std::process::exit(1);
    }

    // 1. Initialize Prometheus & OpenTelemetry Registry
    let registry = prometheus::Registry::new();
    let exporter = opentelemetry_prometheus::exporter()
        .with_registry(registry.clone())
        .build()
        .expect("Failed to build prometheus exporter");
    let meter_provider = opentelemetry_sdk::metrics::SdkMeterProvider::builder()
        .with_reader(exporter)
        .build();
    opentelemetry::global::set_meter_provider(meter_provider);

    // 2. Load NDJSON records into memory
    println!("Loading log entries into memory from {:?}...", args.file);
    let file = File::open(&args.file)?;
    let reader = BufReader::with_capacity(32 * 1024 * 1024, file);

    let mut records: Vec<LogRecord> = Vec::new();
    for line in reader.lines() {
        let line = line?;
        if !line.trim().is_empty() {
            let record: LogRecord = serde_json::from_str(&line)?;
            records.push(record);
        }
    }

    let total_records = records.len();
    println!("Loaded {total_records} records into memory.");
    println!("Cache Capacity: {}", args.capacity);
    println!("Worker Concurrency: {}", args.concurrency);
    println!("Algorithm:              {:?}", args.algorithm);
    let is_realtime = (args.speed - 1.0).abs() < f64::EPSILON;
    println!(
        "Playback Speed: {:.2}x{}",
        args.speed,
        if is_realtime { " (realtime)" } else { "" }
    );
    if let (Some(first), Some(last)) = (records.first(), records.last()) {
        let logged_span_secs = (last.timestamp - first.timestamp).max(0.0);
        println!(
            "Estimated wall time: {:.1}s ({:.1}s of logged traffic at {:.2}x)",
            logged_span_secs / args.speed,
            logged_span_secs,
            args.speed
        );
    }

    // 3. Initialize Cache & Metrics Tracker
    let engine = match args.algorithm {
        Algorithm::Dtac => Engine::Dtac(Arc::new(DtacCache::<String, bytes::Bytes>::new(args.capacity))),
        Algorithm::Lru => Engine::Lru(Arc::new(BaselineLruEngine::<String, bytes::Bytes>::new(args.capacity))),
    };
    let metrics = Arc::new(BenchMetrics::default());
    let default_payload = bytes::Bytes::from(vec![0u8; args.payload_size]);

    let pb = ProgressBar::new(total_records as u64);
    pb.set_style(
        ProgressStyle::default_bar()
            .template("{spinner:.green} [{elapsed_precise}] [{bar:40.cyan/blue}] {pos}/{len} ({per_sec})")?
            .progress_chars("#>-"),
    );

    let mut start_time = Instant::now();
    let mut measurement_started = false;
    let bench_start = TokioInstant::now();
    let semaphore = Arc::new(Semaphore::new(args.concurrency));
    let mut join_set = tokio::task::JoinSet::new();

    // 4. Dispatch records paced by their logged timestamps (scaled by
    //    --speed), while a semaphore bounds how many may be in flight at
    //    once -- decoupling "when a request is paced to start" from "how
    //    many are concurrently executing," matching a real traffic replay.
    for record in records {
        sleep_until(target_instant(bench_start, record.timestamp, args.speed)).await;

        // Warm-up records still exercise the real cache (below) so it gets
        // populated for whichever --algorithm is selected, but the
        // metrics-relevant clock only starts once measurement begins, so
        // throughput/latency/hit-rate numbers reflect a warmed cache, not
        // the warm-up pass itself.
        if !measurement_started && record.phase == Phase::Measurement {
            measurement_started = true;
            start_time = Instant::now();
            pb.println("Warm-up complete -- beginning measurement phase.");
        }

        // If --speed is set too low for the given --concurrency, this is
        // where the dispatch loop will stall waiting for a free slot --
        // intentional backpressure, not a bug.
        let permit = semaphore.clone().acquire_owned().await.expect("semaphore closed");
        let engine = engine.clone();
        let metrics = metrics.clone();
        let pb = pb.clone();
        let payload = default_payload.clone();

        join_set.spawn(async move {
            let _permit = permit; // held for the duration of this task, released on completion

            let is_bot = record.traffic_type == "bot";
            let is_measurement = record.phase == Phase::Measurement;

            // Track total counts per category -- warm-up records still run
            // through the real cache below, but never touch BenchMetrics.
            if is_measurement {
                metrics.total_requests.fetch_add(1, Ordering::Relaxed);
                if is_bot {
                    metrics.bot_requests.fetch_add(1, Ordering::Relaxed);
                } else {
                    metrics.human_requests.fetch_add(1, Ordering::Relaxed);
                }
            }

            let path = record.path.clone();
            let metrics_fetch = metrics.clone();

            // Closure triggered ONLY on a cache miss
            let fetch_from_origin = |_key: &String| {
                let metrics_fetch = metrics_fetch.clone();
                let payload = payload.clone();
                async move {
                    if is_measurement {
                        metrics_fetch.cache_miss_fetches.fetch_add(1, Ordering::Relaxed);
                        if is_bot {
                            metrics_fetch.bot_misses.fetch_add(1, Ordering::Relaxed);
                        } else {
                            metrics_fetch.human_misses.fetch_add(1, Ordering::Relaxed);
                        }
                    }
                    payload
                }
            };

            let req_start = Instant::now();
            let _ = match engine {
                Engine::Dtac(cache) => {
                    // RequestData is only built for the Dtac arm -- the Lru
                    // baseline is bot-unaware by definition, so building it
                    // there would be pure overhead skewing the two
                    // algorithms' measured per-request latency against
                    // each other without affecting hit-rate correctness.
                    let req_data = RequestData {
                        ip_address: resolve_ip(&record.ip),
                        path: record.path,
                        method: record.method,
                        headers: record.headers,
                    };
                    cache.access(path, req_data, fetch_from_origin).await
                }
                Engine::Lru(baseline) => baseline.access(path, fetch_from_origin).await,
            };
            if is_measurement {
                metrics.total_duration_us.fetch_add(req_start.elapsed().as_micros() as u64, Ordering::Relaxed);
            }

            pb.inc(1);
        });
    }

    // Drain remaining in-flight work after the dispatch loop finishes issuing records.
    while join_set.join_next().await.is_some() {}

    pb.finish_with_message("Replay Complete");
    let total_wall_time = start_time.elapsed();

    // 5. Gather and compute final statistics
    print_results(&metrics, total_wall_time, &registry, args.algorithm);

    Ok(())
}

fn print_results(
    m: &BenchMetrics,
    total_time: Duration,
    registry: &prometheus::Registry,
    algorithm: Algorithm,
) {
    let total_reqs = m.total_requests.load(Ordering::Relaxed);
    let total_misses = m.cache_miss_fetches.load(Ordering::Relaxed);
    let total_hits = total_reqs.saturating_sub(total_misses);

    let human_reqs = m.human_requests.load(Ordering::Relaxed);
    let human_misses = m.human_misses.load(Ordering::Relaxed);
    let human_hits = human_reqs.saturating_sub(human_misses);

    let bot_reqs = m.bot_requests.load(Ordering::Relaxed);
    let bot_misses = m.bot_misses.load(Ordering::Relaxed);
    let bot_hits = bot_reqs.saturating_sub(bot_misses);

    let total_us = m.total_duration_us.load(Ordering::Relaxed);
    let avg_latency_us = if total_reqs > 0 { total_us as f64 / total_reqs as f64 } else { 0.0 };
    let rps = total_reqs as f64 / total_time.as_secs_f64();

    let overall_hit_rate = if total_reqs > 0 { (total_hits as f64 / total_reqs as f64) * 100.0 } else { 0.0 };
    let human_hit_rate = if human_reqs > 0 { (human_hits as f64 / human_reqs as f64) * 100.0 } else { 0.0 };
    let bot_hit_rate = if bot_reqs > 0 { (bot_hits as f64 / bot_reqs as f64) * 100.0 } else { 0.0 };

    let report_label = match algorithm {
        Algorithm::Dtac => "DTAC",
        Algorithm::Lru => "STANDARD LRU (BASELINE)",
    };
    println!("\n========================================================");
    println!("          {report_label} DIRECT BENCHMARK REPORT          ");
    println!("          (post-warm-up, steady-state measurement)        ");
    println!("========================================================");
    println!("Elapsed Time:           {:.3?}", total_time);
    println!("Throughput:             {:.2} ops/sec", rps);
    println!("Average Access Time:    {:.3} µs", avg_latency_us);
    println!("--------------------------------------------------------");
    println!("PRIMARY METRIC");
    println!("Human Requests:         {}", human_reqs);
    println!("Human Cache Hit Rate:   {:.2}% ({} hits / {} misses)", human_hit_rate, human_hits, human_misses);
    println!("--------------------------------------------------------");
    println!("SECONDARY METRIC");
    println!("Total Requests:         {}", total_reqs);
    println!("Overall Cache Hit Rate: {} ({:.2}%)", total_hits, overall_hit_rate);
    println!("Total Cache Misses:     {} ({:.2}%)", total_misses, 100.0 - overall_hit_rate);
    println!("--------------------------------------------------------");
    println!("FOR REFERENCE ONLY -- not an optimization target");
    println!("Bot Requests:           {}", bot_reqs);
    println!("Bot Cache Hit Rate:     {:.2}% ({} hits / {} misses)", bot_hit_rate, bot_hits, bot_misses);
    println!("========================================================");

    // Print internal Prometheus metrics gathered by DTAC / OpenTelemetry
    println!("\n--- Raw Prometheus Metrics Registry Output ---");
    let encoder = TextEncoder::new();
    let mut buffer = vec![];
    let metric_families = registry.gather();
    if let Ok(_) = encoder.encode(&metric_families, &mut buffer) {
        if let Ok(text) = String::from_utf8(buffer) {
            println!("{}", text);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn resolve_ip_parses_valid_address() {
        assert_eq!(resolve_ip("203.0.113.5"), IpAddr::V4(Ipv4Addr::new(203, 0, 113, 5)));
    }

    #[test]
    fn resolve_ip_falls_back_on_garbage() {
        assert_eq!(resolve_ip("not-an-ip"), IpAddr::V4(Ipv4Addr::LOCALHOST));
    }

    #[test]
    fn resolve_ip_falls_back_on_missing_default() {
        assert_eq!(resolve_ip(""), IpAddr::V4(Ipv4Addr::LOCALHOST));
    }

    #[test]
    fn phase_defaults_to_measurement_when_absent() -> Result<(), serde_json::Error> {
        let json = r#"{"timestamp":0.0,"method":"GET","path":"/x","headers":{},"traffic_type":"human"}"#;
        let record: LogRecord = serde_json::from_str(json)?;
        assert_eq!(record.phase, Phase::Measurement);
        Ok(())
    }

    #[test]
    fn phase_parses_warmup_and_measurement() -> Result<(), serde_json::Error> {
        let warmup = r#"{"timestamp":0.0,"method":"GET","path":"/x","headers":{},"traffic_type":"human","phase":"warmup"}"#;
        let measurement = r#"{"timestamp":0.0,"method":"GET","path":"/x","headers":{},"traffic_type":"human","phase":"measurement"}"#;
        assert_eq!(serde_json::from_str::<LogRecord>(warmup)?.phase, Phase::Warmup);
        assert_eq!(serde_json::from_str::<LogRecord>(measurement)?.phase, Phase::Measurement);
        Ok(())
    }

    #[tokio::test]
    async fn target_instant_scales_with_speed() {
        let start = TokioInstant::now();
        let at_1x = target_instant(start, 10.0, 1.0);
        let at_10x = target_instant(start, 10.0, 10.0);
        assert!(at_10x < at_1x);
        assert_eq!(at_10x, start + Duration::from_secs_f64(1.0));
    }

    #[tokio::test]
    async fn baseline_lru_hit_after_miss_does_not_refetch() {
        let engine = BaselineLruEngine::<String, i32>::new(1);
        let fetches = AtomicU64::new(0);

        let miss = engine
            .access("only-key".to_string(), |_k| {
                fetches.fetch_add(1, Ordering::Relaxed);
                async { 42 }
            })
            .await;
        assert_eq!(miss, 42);
        assert_eq!(fetches.load(Ordering::Relaxed), 1);

        let hit = engine
            .access("only-key".to_string(), |_k| {
                fetches.fetch_add(1, Ordering::Relaxed);
                async { -1 } // would prove this ran if it did
            })
            .await;
        assert_eq!(hit, 42);
        assert_eq!(fetches.load(Ordering::Relaxed), 1); // fetch not called again
    }

    #[tokio::test]
    async fn baseline_lru_evicts_least_recently_used_within_a_shard() {
        // DefaultHasher is fixed-seed, so shard assignment is deterministic;
        // brute-force three candidate keys that collide into the same shard
        // so recency-ordered (not just capacity-1-swap) eviction is
        // observable, without depending on shard-count internals beyond
        // what BaselineLruEngine already exposes.
        let mut by_shard: HashMap<usize, Vec<String>> = HashMap::new();
        for i in 0..5000 {
            let key = format!("k{i}");
            let shard = BaselineLruEngine::<String, i32>::get_shard_id(&key);
            by_shard.entry(shard).or_default().push(key);
        }
        let (key_a, key_b, key_c) = by_shard
            .values()
            .find(|keys| keys.len() >= 3)
            .map(|keys| (keys[0].clone(), keys[1].clone(), keys[2].clone()))
            .expect("5000 candidate keys across 256 shards must collide 3-deep somewhere");

        // total_capacity = 2 * NUM_SHARDS -> capacity_per_shard == 2.
        let engine = BaselineLruEngine::<String, i32>::new(2 * NUM_SHARDS);

        let _ = engine.access(key_a.clone(), |_k| async { 1 }).await; // shard (MRU->LRU): [A]
        let _ = engine.access(key_b.clone(), |_k| async { 2 }).await; // shard: [B, A]
        let _ = engine.access(key_a.clone(), |_k| async { 1 }).await; // hit: promotes A -> shard: [A, B]
        let _ = engine.access(key_c.clone(), |_k| async { 3 }).await; // miss, over capacity: evicts LRU (B) -> shard: [C, A]

        // Check key_a's survival BEFORE checking key_b: verifying a miss is
        // itself a cache-mutating access (it re-inserts the key), so
        // checking key_b first would evict key_a all over again and
        // invalidate this assertion order.
        let refetch_a = AtomicU64::new(0);
        let a_again = engine
            .access(key_a.clone(), |_k| {
                refetch_a.fetch_add(1, Ordering::Relaxed);
                async { 99 }
            })
            .await;
        assert_eq!(a_again, 1); // original value, not 99 -- key_a survived as a hit
        assert_eq!(refetch_a.load(Ordering::Relaxed), 0);

        let refetch_b = AtomicU64::new(0);
        let b_again = engine
            .access(key_b.clone(), |_k| {
                refetch_b.fetch_add(1, Ordering::Relaxed);
                async { -1 }
            })
            .await;
        assert_eq!(b_again, -1);
        assert_eq!(refetch_b.load(Ordering::Relaxed), 1); // confirms key_b was evicted
    }
}